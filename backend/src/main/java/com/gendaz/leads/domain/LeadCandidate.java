package com.gendaz.leads.domain;

public class LeadCandidate {

    private String businessName;
    private String category;
    private String address;
    private String city;
    private String state;
    private String country;
    private String phone;
    private String email;
    private String website;
    private String instagramUsername;
    private String instagramUrl;
    private String instagramStatus = "NOT_FOUND";
    private String source;
    private String sourceId;

    public LeadCandidate() {
    }

    public LeadCandidate(String businessName, String source, String sourceId) {
        this.businessName = businessName;
        this.source = source;
        this.sourceId = sourceId;
    }

    public String getBusinessName() {
        return businessName;
    }

    public void setBusinessName(String businessName) {
        this.businessName = businessName;
    }

    public String getCategory() {
        return category;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getCity() {
        return city;
    }

    public void setCity(String city) {
        this.city = city;
    }

    public String getState() {
        return state;
    }

    public void setState(String state) {
        this.state = state;
    }

    public String getCountry() {
        return country;
    }

    public void setCountry(String country) {
        this.country = country;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getWebsite() {
        return website;
    }

    public void setWebsite(String website) {
        this.website = website;
    }

    public String getSource() {
        return source;
    }

    public void setSource(String source) {
        this.source = source;
    }

    public String getSourceId() {
        return sourceId;
    }

    public void setSourceId(String sourceId) {
        this.sourceId = sourceId;
    }

    public String getInstagramUsername() {
        return instagramUsername;
    }

    public void setInstagramUsername(String instagramUsername) {
        this.instagramUsername = instagramUsername;
    }

    public String getInstagramUrl() {
        return instagramUrl;
    }

    public void setInstagramUrl(String instagramUrl) {
        this.instagramUrl = instagramUrl;
    }

    public String getInstagramStatus() {
        return instagramStatus;
    }

    public void setInstagramStatus(String instagramStatus) {
        this.instagramStatus = instagramStatus;
    }
}
